// Writes the last git commit date (ISO) to data/build-meta.ts before build, so
// the sitemap reports when the content actually changed — not the build time.
// Falls back to the current date when git history isn't available.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let iso;
try {
  iso = execSync("git log -1 --format=%cI", { encoding: "utf8" }).trim();
  if (!iso) throw new Error("empty");
} catch {
  iso = new Date().toISOString();
}

const out = `// AUTO-GENERATED by scripts/gen-lastmod.mjs — do not edit.
export const LAST_MODIFIED = ${JSON.stringify(iso)};
`;
writeFileSync(new URL("../data/build-meta.ts", import.meta.url), out);
console.log(`[lastmod] ${iso}`);
